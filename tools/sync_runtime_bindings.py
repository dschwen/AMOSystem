#!/usr/bin/env python3
"""Generate checked runtime thunks beside their actual function definitions.

Ownership is source metadata, not guessed prototypes. --bootstrap initializes
it from an existing host build's symbol table; normal generation needs no build.
"""
import argparse
from collections import defaultdict
import json
from pathlib import Path
import re
import subprocess
ROOT = Path(__file__).resolve().parents[1]
OWNERS = ROOT/'src/runtime/bindings/owners.json'
PATTERN = re.compile(r'GlueKind::(\w+), (?:reinterpret_cast<const void \*>\(&([\w:]+)\)|AMOS_BIND_\w+\(([\w:]+)\)), nullptr, (\d+), (\d+),')
NAMESPACES = ('boot', 'dbl', 'dev', 'ed', 'ffp', 'host', 'interp', 'menu', 'monitor', 'music', 'verif', 'w')
CATEGORY = {'libcall':'LIBRARY', 'reg':'REG', 'call':'CALL', 'test':'CALL', 'record':'CALL',
            'eval':'EVAL', 'eval_d3':'EVAL', 'float_':'FLOAT', 'w':'W', 'w_a0':'W',
            'w_f':'W_RESULT', 'hand':'HAND', 'c_routine':'UNSUPPORTED'}
PROTOTYPES = {'LIBRARY':'uint64_t {name}(const uint32_t*)', 'REG':'uint32_t {name}(amos::RegFrame&)',
              'CALL':'void {name}()', 'EVAL':'void {name}(amos::interp::EvalOut*)',
              'FLOAT':'void {name}(uint32_t*)', 'W':'void {name}(amos::AllRegs*)',
              'W_RESULT':'uint32_t {name}(amos::AllRegs*)', 'HAND':'void {name}(amos::AllRegs&)'}
BODIES = {'REG':'return detail::typed_reg_call<&{fn}>(r);', 'CALL':'{fn}();', 'EVAL':'{fn}(out);',
          'FLOAT':'detail::typed_float_call<&{fn}>(words);', 'W':'{fn}(r);',
          'W_RESULT':'return uint32_t({fn}(r));', 'HAND':'{fn}(r);'}
PARAMETERS = {'REG':'RegFrame& r', 'CALL':'', 'EVAL':'interp::EvalOut* out',
              'FLOAT':'uint32_t* words', 'W':'AllRegs* r', 'W_RESULT':'AllRegs* r', 'HAND':'AllRegs& r'}
RETURNS = {'REG':'uint32_t', 'CALL':'void', 'EVAL':'void', 'FLOAT':'void',
           'W':'void', 'W_RESULT':'uint32_t', 'HAND':'void'}

def generate(bootstrap=False, check=False):
    entries = defaultdict(set)
    outputs = {}
    for path in sorted((ROOT/'src/tables').glob('*.cpp')):
        text = path.read_text()
        for kind, old, new, count, result in PATTERN.findall(text):
            fn = old or new
            category = CATEGORY[kind]
            if category != 'UNSUPPORTED':
                entries[fn].add((category, int(count) if kind == 'libcall' else 0,
                                (0 if result == '3' else 8 if result == '4' else 4) if kind == 'libcall' else 0))
        def replace(match):
            kind, old, new, count, result = match.groups()
            return f'GlueKind::{kind}, AMOS_BIND_{CATEGORY[kind]}({old or new}), nullptr, {count}, {result},'
        replaced = PATTERN.sub(replace, text)
        replaced = re.sub(r'\s+AMOS_TYPED_LIBCALL\(\w+\)', '', replaced)
        if replaced != text: outputs[path] = replaced
    if bootstrap:
        symbols = subprocess.check_output(['nm', '-A', '-C', '--defined-only',
                                          *map(str, sorted((ROOT/'build/host/obj/src').glob('*/*.o')))], text=True)
        owners = {}
        for line in symbols.splitlines():
            match = re.match(r'([^:]+):\S+\s+[Tt]\s+(.+)$', line)
            if not match: continue
            fn = match[2].split('(')[0].split('::')[-1]
            if fn in entries:
                owners[fn] = str(Path(match[1]).relative_to(ROOT/'build/host/obj').with_suffix('.cpp'))
        if set(owners) != set(entries): raise ValueError('unresolved implementations: '+str(sorted(set(entries)-set(owners))))
        OWNERS.write_text(json.dumps(owners, indent=2, sort_keys=True)+'\n')
    owners = json.loads(OWNERS.read_text())
    if set(entries) != set(owners): raise ValueError('entry/ownership metadata drift')
    by_source = defaultdict(list)
    declarations = ['// Generated by tools/sync_runtime_bindings.py; no erased prototypes.',
                    '#pragma once', '#include "runtime/native_binding.h"', 'extern "C" {']
    for fn, signatures in sorted(entries.items()):
        if len(signatures) != 1: raise ValueError(f'incompatible signatures for {fn}: {signatures}')
        category, arity, width = next(iter(signatures))
        declarations.append(PROTOTYPES[category].format(name='amos_typed_'+fn)+';')
        by_source[owners[fn]].append((fn, category, arity, width))
    declarations.append('}')
    outputs[ROOT/'src/runtime/native_bindings.h'] = '\n'.join(declarations)+'\n'
    for source, functions in sorted(by_source.items()):
        include = Path('runtime/bindings')/(Path(source).parent.name+'_'+Path(source).stem+'.inc')
        body = ['// Generated in the defining TU: the compiler sees the real signature.',
                '#include "runtime/typed_call.h"', '#include "interp/interp.h"', 'namespace amos {']
        body += [f'namespace {ns} {{}}' for ns in NAMESPACES]
        body += ['}', 'namespace amos::host {', 'using namespace ::amos;']
        body += [f'using namespace ::amos::{ns};' for ns in NAMESPACES if ns != 'host']
        body += ['extern "C" {']
        for fn, category, arity, width in functions:
            if category == 'LIBRARY':
                body.append(f'uint64_t amos_typed_{fn}(const uint32_t* words) {{ return typed_library_call<&{fn}, {arity}, {width}>(words); }}')
            else:
                statement = BODIES[category].format(fn=fn)
                body.append(f'{RETURNS[category]} amos_typed_{fn}({PARAMETERS[category]}) {{ {statement} }}')
        body += ['}', '}']
        outputs[ROOT/'src'/include] = '\n'.join(body)+'\n'
        path = ROOT/source
        marker = f'#include "{include}"'
        text = path.read_text()
        if marker not in text:
            outputs[path] = text.rstrip()+f'\n\n#if !defined(__mc68000__)\n{marker}\n#endif\n'
    errors = []
    for path, text in outputs.items():
        if check:
            if not path.exists() or path.read_text() != text: errors.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if errors: raise ValueError('stale generated bindings: '+', '.join(errors))
    print(f'{len(entries)} typed bindings in {len(by_source)} implementation units: '+('verified' if check else 'generated'))
if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bootstrap', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generate(args.bootstrap, args.check)
