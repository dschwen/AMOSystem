#!/usr/bin/env python3
"""The C++ functions behind the WEntry glue, for direct calls.

  wentry_table.py --out wentry_table.cpp GLUE.s...

Every "_entry WEntry _cfunction" (WEntryA0, WEntryF) of the glue files
(w/wglue.i) is an entry that hands all the registers to
cfunction(AllRegs *). The output is amos::wentry_table, the pairs of
both, which main/direct.cpp sorts and searches: calls to such an entry
from C++ (the editor's and the monitor's call()) then call the function
directly.
"""

import argparse
import re

ap = argparse.ArgumentParser()
ap.add_argument('--out', required=True)
ap.add_argument('glue', nargs='+')
args = ap.parse_args()

pairs = {}
for path in sorted(args.glue):
    for line in open(path, encoding='latin-1'):
        m = re.match(r'^_(\w+)\s+WEntry\w*\s+_(\w+)', line)
        if m:
            pairs[m.group(1)] = m.group(2)

with open(args.out, 'w') as f:
    f.write('// Generated by tools/wentry_table.py from the WEntry lines of src/*/*_glue.s\n')
    f.write('#include "core/amos.h"\n\n')
    f.write('extern "C" {\n')
    for entry in sorted(pairs):
        f.write(f'extern uint8_t {entry}[];\n')
    for fn in sorted(set(pairs.values())):
        f.write(f'void {fn}(amos::AllRegs *);\n')
    f.write('}\n\nnamespace amos {\n\n')
    f.write(f'WEntryPair wentry_table[{len(pairs)}] = {{\n')
    for entry in sorted(pairs):
        f.write(f'    {{{entry}, {pairs[entry]}}},\n')
    f.write(f'}};\nextern const int wentry_count;\nconst int wentry_count = {len(pairs)};\n\n}} // namespace amos\n')
