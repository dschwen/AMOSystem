#!/usr/bin/env python3
"""The usa keymap of a Kickstart (the one the console device uses), as C++
for the host build.

  extract_keymap.py --out keymap.cpp [--rom KICKSTART] [--key ROM.KEY]

Finds the KeyMapNode named "usa" in the ROM image (a Cloanto-encrypted one
is decrypted with its rom.key) and writes the low half of its KeyMap: the
key types, the map (a dead key's entry an offset into the dead keys'
descriptors), the capsable bits, and the descriptors with their tables.
Without a ROM the result has no keymap, and the host uses a table of its
own (no Alt characters, no dead keys). The result is the ROM's data: it
stays in build/, not to be distributed.
"""

import argparse
import os
import struct

ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument('--out', required=True)
ap.add_argument('--rom')
ap.add_argument('--key')
args = ap.parse_args()

KCF_DEAD = 0x20


def load():
    if not args.rom or not os.path.exists(args.rom):
        return None
    data = open(args.rom, 'rb').read()
    if data.startswith(b'AMIROMTYPE1'):
        if not args.key or not os.path.exists(args.key):
            return None
        key = open(args.key, 'rb').read()
        data = bytes(b ^ key[i % len(key)] for i, b in enumerate(data[11:]))
    return data


def keymap(rom):
    """(types, map, capsable, descriptors) of the ROM's usa keymap, or None"""
    base = 0x1000000 - len(rom)
    name = rom.find(b'usa\0')
    while name >= 0:
        target = struct.pack('>I', base + name)
        at = rom.find(target)
        while at >= 0:
            # KeyMapNode: the name is its ln_Name (at 10), the KeyMap follows (at 14)
            km = struct.unpack('>8I', rom[at + 4:at + 36])
            if all(base <= p < 0x1000000 for p in km):
                types = rom[km[0] - base:km[0] - base + 64]
                lmap = list(struct.unpack('>64I', rom[km[1] - base:km[1] - base + 256]))
                caps = rom[km[2] - base:km[2] - base + 8]
                dead = [lmap[k] for k in range(64) if types[k] & KCF_DEAD]
                if dead and all(base <= p < 0x1000000 for p in dead):
                    start, end = min(dead), max(dead) + 64
                    blob = rom[start - base:end - base]
                    for k in range(64):
                        if types[k] & KCF_DEAD:
                            lmap[k] -= start
                    return types, lmap, caps, blob
            at = rom.find(target, at + 2)
        name = rom.find(b'usa\0', name + 1)
    return None


rom = load()
found = keymap(rom) if rom else None
with open(args.out, 'w') as f:
    f.write('// Generated by tools/extract_keymap.py from the user\'s Kickstart: not to\n')
    f.write('// be distributed\n#include <stdint.h>\n\nnamespace amos::host {\n\n')
    f.write('struct RomKeymap {\n    const uint8_t *types;\n    const uint32_t *map;\n'
            '    const uint8_t *capsable, *dead;\n};\n\n')
    f.write('extern const RomKeymap rom_keymap;\n')
    if found:
        types, lmap, caps, blob = found
        f.write(f'static const uint8_t types[] = {{{",".join(str(b) for b in types)}}};\n')
        f.write(f'static const uint32_t map[] = {{{",".join(str(v) for v in lmap)}}};\n')
        f.write(f'static const uint8_t capsable[] = {{{",".join(str(b) for b in caps)}}};\n')
        f.write(f'static const uint8_t dead[] = {{{",".join(str(b) for b in blob)}}};\n')
        f.write('const RomKeymap rom_keymap = {types, map, capsable, dead};\n')
    else:
        f.write('const RomKeymap rom_keymap = {nullptr, nullptr, nullptr, nullptr};\n')
    f.write('\n} // namespace amos::host\n')
print('extract_keymap: ' + ('the usa keymap' if found else 'no keymap (no Kickstart: KICKSTART=, ROMKEY=)'))
