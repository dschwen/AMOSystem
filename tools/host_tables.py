#!/usr/bin/env python3
"""The assembler's symbols for a build on another host (src/host).

  host_tables.py --out host_symbols.cpp --implemented NAME... -- ASM...

On the Amiga, the C++ refers to labels of the assembler: entries of glue
(WEntry), tables, records. Another host has no assembler: each label the
C++ may refer to (each xdef'd "_name" of the given sources) becomes a
small object of its own here, an address the C++ keeps and compares as
on the Amiga; the WEntry table (build/gen/wentry_table.cpp) maps those of
the glue to their C++ functions, which src/host/bridge.cpp calls. The
names --implemented (the assembler functions src/host implements in C++)
are left out.
"""

import argparse
import re

ap = argparse.ArgumentParser()
ap.add_argument('--out', required=True)
ap.add_argument('--implemented', nargs='*', default=[])
ap.add_argument('sources', nargs='+')
args = ap.parse_args()

names = set()
for path in args.sources:
    for line in open(path, encoding='latin-1'):
        code = line.split(';')[0]
        m = re.match(r'\s+xdef\s+(.*)', code, re.I)
        if m:
            for n in m.group(1).split(','):
                n = n.strip()
                if n.startswith('_') and '\\' not in n:
                    names.add(n[1:])
        m = re.match(r'\s+(?:RegRoutine|LibRoutine|LibEntry)\s+(_\w+)', code)
        if m:
            names.add(m.group(1)[1:])
        m = re.match(r'\s+PrgEntry\s+(\w+)', code)
        if m:
            names.add(f'ver_prg_{m.group(1)}_entry')
        m = re.match(r'\s+VerEntry\s+(\w+)', code)
        if m:
            names.add(f'ver_{m.group(1)}_entry')
names -= set(args.implemented)

with open(args.out, 'w') as f:
    f.write('// Generated by tools/host_tables.py: the assembler labels the C++ may\n')
    f.write('// refer to, as objects of their own on another host\n')
    f.write('#include <stdint.h>\n\nextern "C" {\n')
    for n in sorted(names):
        f.write(f'uint8_t {n}[4] __attribute__((aligned(4)));\n')
    f.write('}\n')
