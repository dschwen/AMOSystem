#!/usr/bin/env python3
"""The C++ functions behind AMOSPro.Lib routines, for direct calls.

  lib_direct.py --out lib_direct.cpp --routines lib_routines.h GLUE.s...

Every "RegRoutine Name,_cfunction" of the glue files is a library routine
whose code is cfunction(RegFrame &). The output is the table
amos::lib_direct[Lib_Size]: for each routine number, its function or null.
The entries table (assembler, amos::lib_direct_entry) holds the glue's
address of each: lib_call() (core/amos.h) calls the function directly
when the jump table still points to that glue (the float routines are
swapped in the table), instead of going through the table and the glue.
"""

import argparse
import re

ap = argparse.ArgumentParser()
ap.add_argument('--out', required=True)
ap.add_argument('--entries', required=True, help='the .s table of the glue entries')
ap.add_argument('--routines', required=True)
ap.add_argument('glue', nargs='+')
args = ap.parse_args()

numbers = {}
size = None
for line in open(args.routines):
    m = re.match(r'constexpr int (L_\w+) = (\d+);', line)
    if m:
        numbers[m.group(1)] = int(m.group(2))
    m = re.match(r'constexpr int Lib_Size = (\d+);', line)
    if m:
        size = int(m.group(1))

table = {}
for path in sorted(args.glue):
    for line in open(path, encoding='latin-1'):
        m = re.match(r'\s+RegRoutine\s+([\w.]+)\s*,\s*_(\w+)', line)
        if not m:
            continue
        name = 'L_' + m.group(1).replace('.', '_')
        if name in numbers:
            table[numbers[name]] = (m.group(2), m.group(1))

functions = sorted({fn for fn, label in table.values()})
with open(args.out, 'w') as f:
    f.write('// Generated by tools/lib_direct.py from the RegRoutine lines of src/*/*_glue.s\n')
    f.write('#include "core/amos.h"\n\n')
    f.write('extern "C" {\n')
    for fn in functions:
        f.write(f'uint32_t {fn}(amos::RegFrame &);\n')
    f.write('}\n\nnamespace amos {\n\n')
    f.write(f'const RegFunction lib_direct[{size}] = {{\n')
    for i in range(size):
        f.write(f'    {table[i][0] if i in table else "nullptr"},\n')
    f.write('};\n\n} // namespace amos\n')

with open(args.entries, 'w') as f:
    f.write('; Generated by tools/lib_direct.py: the glue of each library routine\n')
    f.write('; with a C++ function (amos::lib_direct_entry), or 0\n')
    f.write('\t\tSECTION\t.data,DATA\n\n')
    labels = sorted({label for fn, label in table.values()})
    for label in labels:
        f.write(f'\t\tXREF\t{label}\n')
    f.write('\t\txdef\t__ZN4amos16lib_direct_entryE\n__ZN4amos16lib_direct_entryE\n')
    for i in range(size):
        f.write(f'\t\tdc.l\t{table[i][1] if i in table else 0}\n')
