#!/usr/bin/env python3
"""The C++ functions behind AMOS.library's vector tables, for direct calls.

  w_direct.py --out w_direct.cpp +W.s GLUE.s...

The SyCall and EcCall tables of +W.s (SyIn, EcIn) are "bra Label" entries;
Label is "jmp _entry", and _entry (src/w/*_glue.s) "WEntry _cfunction"
(WEntryA0, WEntryF): cfunction(AllRegs *) is the function. The output is
the tables amos::sy_direct and amos::ec_direct: for each function number,
its C++ function or null. sy_call() and ec_call() (core/amos.h) call it
directly while the vectors are AMOS.library's own (the monitor patches
them).
"""

import argparse
import re

ap = argparse.ArgumentParser()
ap.add_argument('--out', required=True)
ap.add_argument('wsource')
ap.add_argument('glue', nargs='+')
args = ap.parse_args()

lines = open(args.wsource, encoding='latin-1').read().split('\n')
jumps = {}
for l in lines:
    m = re.match(r'^([A-Za-z_][\w.]*):?\s+jmp\s+(_\w+)', l)
    if m:
        jumps[m.group(1).lower()] = m.group(2)
entries = {}
for path in args.glue:
    for l in open(path, encoding='latin-1'):
        m = re.match(r'^(_\w+)\s+WEntry\w*\s+_(\w+)', l)
        if m:
            entries[m.group(1)] = m.group(2)


def table(label):
    start = next(i for i, l in enumerate(lines) if re.match(label + r':?\s', l))
    out = []
    for l in lines[start:]:
        m = re.match(r'^(?:\w+:?)?\s+bra\s+([\w.]+)', l.split(';')[0])
        if not m:
            break
        target = jumps.get(m.group(1).lower())
        out.append(entries.get(target) if target else None)
    return out


tables = {'sy': table('SyIn'), 'ec': table('EcIn')}
functions = sorted({f for t in tables.values() for f in t if f})
with open(args.out, 'w') as f:
    f.write('// Generated by tools/w_direct.py from +W.s and src/w/*_glue.s\n')
    f.write('#include "core/amos.h"\n\n')
    f.write('extern "C" {\n')
    for fn in functions:
        f.write(f'void {fn}(amos::AllRegs *);\n')
    f.write('}\n\nnamespace amos {\n')
    for name, t in tables.items():
        f.write(f'\nconst WFunction {name}_direct[{len(t)}] = {{\n')
        for fn in t:
            f.write(f'    {fn or "nullptr"},\n')
        f.write('};\n')
    f.write('\n} // namespace amos\n')
