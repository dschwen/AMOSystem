#!/usr/bin/env python3
"""The topaz fonts of a Kickstart, as C++ for the host build.

  extract_topaz.py --out topaz.cpp [--rom KICKSTART] [--key ROM.KEY]
                   [--fallback data/fonts/topaz8]

Finds topaz 8 and 9 in the ROM image (a Cloanto-encrypted one is
decrypted with its rom.key) and writes them as host::rom_fonts
(host/fonts.cpp): their sizes, baseline, characters, the bitmap and the
characters' places. Without a ROM, topaz 8 is the raw font of --fallback
(AROS's topaz 8, data/fonts/topaz8: its README), and topaz 9 is drawn with
its characters. The output can hold the user's ROM: it stays in build/.
"""

import argparse
import os
import struct

ap = argparse.ArgumentParser()
ap.add_argument('--out', required=True)
ap.add_argument('--rom')
ap.add_argument('--key')
ap.add_argument('--fallback', help='a raw topaz 8 (chardata.bin, charloc.bin) for no ROM')
args = ap.parse_args()


def load():
    if not args.rom or not os.path.exists(args.rom):
        return None
    data = open(args.rom, 'rb').read()
    if data.startswith(b'AMIROMTYPE1'):
        if not args.key or not os.path.exists(args.key):
            return None
        key = open(args.key, 'rb').read()
        data = bytes(b ^ key[i % len(key)] for i, b in enumerate(data[11:]))
    return data


def fonts(rom):
    """The TextFonts of the ROM of 8 and 9 lines, characters 32-255, their
    data and tables in the ROM. (Topaz 8's names "topaz.font"; topaz 9's
    name field is not set in the ROM, the system sets it.)"""
    base = 0x1000000 - len(rom)
    found = {}
    for at in range(0, len(rom) - 52, 2):
        ysize, style, flags, xsize, baseline, smear = struct.unpack('>HBBHHH', rom[at + 20:at + 30])
        lo, hi = rom[at + 32], rom[at + 33]
        data, modulo, loc = struct.unpack('>IHI', rom[at + 34:at + 44])
        if ysize not in (8, 9) or ysize in found or (lo, hi) != (32, 255) or not 6 <= xsize <= 16:
            continue
        if not (base <= data < 0x1000000 and base <= loc < 0x1000000) or modulo < xsize * 12:
            continue
        chars = hi - lo + 2
        bitmap = rom[data - base:data - base + modulo * ysize]
        locs = struct.unpack(f'>{chars}I', rom[loc - base:loc - base + 4 * chars])
        # every glyph inside the bitmap's rows
        if any((v >> 16) + (v & 0xFFFF) > modulo * 8 for v in locs):
            continue
        found[ysize] = (style, flags, xsize, baseline, smear, lo, hi, modulo, bitmap, locs)
    return found


rom = load()
found = fonts(rom) if rom else {}
source = 'the Kickstart' if found else ''
if 8 not in found and args.fallback:
    # the raw TextFont of data/fonts/topaz8 (AROS): 8x8, baseline 6, 32-255
    bitmap = open(os.path.join(args.fallback, 'chardata.bin'), 'rb').read()
    loc = open(os.path.join(args.fallback, 'charloc.bin'), 'rb').read()
    locs = struct.unpack(f'>{len(loc) // 4}I', loc)
    found[8] = (0, 0x41, 8, 6, 1, 32, 255, len(bitmap) // 8, bitmap, locs)
    source = 'AROS (' + args.fallback + ')'

with open(args.out, 'w') as f:
    f.write(f'// Generated by tools/extract_topaz.py from {source or "nothing"}' +
            (': not to be distributed\n' if source == 'the Kickstart' else '\n'))
    f.write('#include <stdint.h>\n\nnamespace amos::host {\n\n')
    f.write('struct RomFont {\n    uint16_t ysize, xsize, baseline, boldsmear, modulo;\n')
    f.write('    uint8_t style, flags, lo, hi;\n    const uint8_t *data;\n    const uint32_t *locs;\n};\n\n')
    for ysize, (style, flags, xsize, baseline, smear, lo, hi, modulo, bitmap, locs) in sorted(found.items()):
        f.write(f'static const uint8_t topaz{ysize}_data[] = {{{",".join(str(b) for b in bitmap)}}};\n')
        f.write(f'static const uint32_t topaz{ysize}_locs[] = {{{",".join(str(v) for v in locs)}}};\n')
    f.write('\nextern const RomFont rom_fonts[];\nextern const int rom_font_count;\n')
    f.write('const RomFont rom_fonts[] = {\n')
    for ysize, (style, flags, xsize, baseline, smear, lo, hi, modulo, bitmap, locs) in sorted(found.items()):
        f.write(f'    {{{ysize}, {xsize}, {baseline}, {smear}, {modulo}, {style}, {flags}, {lo}, {hi}, '
                f'topaz{ysize}_data, topaz{ysize}_locs}},\n')
    if not found:
        f.write('    {0, 0, 0, 0, 0, 0, 0, 0, 0, nullptr, nullptr},\n')
    f.write(f'}};\nconst int rom_font_count = {len(found)};\n\n}} // namespace amos::host\n')
print(f'extract_topaz: {len(found)} fonts' + (f' from {source}' if found else ' (no Kickstart: KICKSTART=, ROMKEY=)'))
